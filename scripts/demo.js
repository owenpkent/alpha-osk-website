/* ---------------------------------------------------------------------------
   The live prediction demo on alphaosk.com
   ---------------------------------------------------------------------------
   Click the keys and the pills above them fill in, including through a
   mis-click. This is a JavaScript reimplementation of the approach the
   application takes, not the Python engine compiled to the web: the site says
   so in as many words, because claiming otherwise would be the dishonest
   version of a marketing demo.

   What IS the same is the data and the constants. scripts/demo-data.js is
   generated by tools/gen_demo_data.py straight out of the app repo's own
   wordlist and curated bigrams, through the same fragment filter, and every
   number below is the value the shipped engine uses, named here so the two can
   be diffed:

     KEY_SIGMA          fuzzy_recognizer.SpatialEmissions.KEY_SIGMA
     FREQ_WEIGHT        prefix_beam.PrefixBeam.FREQ_WEIGHT
     LOG_OMIT/LOG_EXTRA prefix_beam.PrefixBeam.LOG_OMIT / LOG_EXTRA
     FREQUENCY_MAY_BUY  prefix_beam.PrefixBeam.FREQUENCY_MAY_BUY
     POS                fuzzy_recognizer.QWERTY_POSITIONS

   What is deliberately NOT here: learning from what you type (the demo forgets
   everything on reload and nothing leaves the page), the pointer-bias model,
   structured tokens, and the PPM character model, which is out of the shipped
   merge anyway.
--------------------------------------------------------------------------- */

(function () {
  "use strict";

  /* ---------- Constants, all mirrored from the application ---------- */

  // Emission width when only the key is known: somewhere inside it, plus
  // scatter. An exact hit costs 0 and an adjacent key costs -0.69.
  var KEY_SIGMA = 0.85;

  // Weight on log1p(freq) when ranking completions of a path.
  var FREQ_WEIGHT = 0.55;

  // Per-edit path costs. Omission and extra pull against each other; -2.5
  // leans toward omission, the dominant error for this kind of input.
  var LOG_OMIT = -2.5;
  var LOG_EXTRA = -3.4;
  var LOG_TRANSPOSE = -1.0;

  // A candidate reached only by paths costing more than one cheap edit is
  // placed below the typed prefix's own completions rather than bought past
  // them by frequency. An adjacent slip is -0.69 and a swap -1.0, so both still
  // compete on frequency; two slips do not.
  var FREQUENCY_MAY_BUY = -1.5;

  // Below three characters the exact prefix is the better source, so the fuzzy
  // pass does not run at all. Same guard the application applies.
  var MIN_FUZZY_PREFIX = 3;

  // How many keystrokes more than the target word the fuzzy pass will still
  // consider. The prune below is there to stop short words being aligned
  // against everything, but at zero it excluded the target of the commonest
  // error this panel exists to show: "helllo" is six characters, so "hello"
  // was dropped before alignScore ever saw it, even though it aligns at -3.4,
  // well inside the cutoff. A doubled tap is a leading error mode for the
  // people this product is for, so it has to survive the prune.
  var MAX_EXTRA_KEYS = 2;

  var MAX_PILLS = 5;

  // The one number here that is NOT taken from the application, and it is worth
  // saying why. The shipped engine ranks against the user's own vocabulary and
  // the live context of the sentence so far, and that is most of what separates
  // "then" from "run" once three characters are down. A page that has neither
  // has to lean harder on the keys actually pressed, so a candidate that does
  // not begin with the letter that was actually typed pays this. It is also
  // defensible on its own terms: the first key of a word is the one press with
  // no movement carried into it from a previous key, so it is the least likely
  // to be the slipped one. The cost is that a slip on the very first key is
  // demoted rather than recovered; every later key still recovers fully.
  var FIRST_KEY_ANCHOR = -1.6;

  // fuzzy_recognizer.QWERTY_POSITIONS, letters only. Row, then column, in key
  // widths, with the physical stagger of a real board.
  var POS = {
    q: [0, 0], w: [0, 1], e: [0, 2], r: [0, 3], t: [0, 4],
    y: [0, 5], u: [0, 6], i: [0, 7], o: [0, 8], p: [0, 9],
    a: [1, 0.25], s: [1, 1.25], d: [1, 2.25], f: [1, 3.25], g: [1, 4.25],
    h: [1, 5.25], j: [1, 6.25], k: [1, 7.25], l: [1, 8.25],
    z: [2, 0.75], x: [2, 1.75], c: [2, 2.75], v: [2, 3.75],
    b: [2, 4.75], n: [2, 5.75], m: [2, 6.75]
  };

  var ROWS = [
    "qwertyuiop".split(""),
    "asdfghjkl".split(""),
    "zxcvbnm".split("")
  ];

  /* ---------- Model ---------- */

  var WORDS = [];      // frequency rank order, most common first
  var RANK = {};       // word -> index
  var BIGRAMS = {};    // previous word -> [likely next words]
  var BY_FIRST = {};   // first letter -> [word indices], for pruning
  var NEIGHBOURS = {}; // letter -> letters within 1.5 key widths

  function freqOf(index) {
    // The application derives a count from rank rather than storing one:
    // frequency = listLength - rank. Keeping that here means the generated
    // data file needs no frequency column.
    return WORDS.length - index;
  }

  function freqScore(index) {
    return FREQ_WEIGHT * Math.log1p(freqOf(index));
  }

  function dist2(a, b) {
    var p = POS[a], q = POS[b];
    if (!p || !q) return null;
    var dr = p[0] - q[0], dc = p[1] - q[1];
    return dr * dr + dc * dc;
  }

  // log P(typed | intended), unnormalised so that a hit costs exactly 0. That
  // is what stops a long accurate typing from pruning out and stops an edge key
  // outscoring a central one for equal accuracy.
  function subCost(typed, intended) {
    if (typed === intended) return 0;
    var d2 = dist2(typed, intended);
    if (d2 === null) return -8;
    return -d2 / (2 * KEY_SIGMA * KEY_SIGMA);
  }

  function buildIndexes() {
    var i, letter;
    RANK = {};
    BY_FIRST = {};
    for (i = 0; i < WORDS.length; i++) {
      RANK[WORDS[i]] = i;
      letter = WORDS[i].charAt(0);
      (BY_FIRST[letter] || (BY_FIRST[letter] = [])).push(i);
    }
    var letters = Object.keys(POS);
    letters.forEach(function (a) {
      NEIGHBOURS[a] = letters.filter(function (b) {
        var d2 = dist2(a, b);
        return d2 !== null && d2 <= 2.25; // within 1.5 key widths
      });
    });
  }

  /* ---------- Prediction ---------- */

  // Best alignment of the whole typed prefix against some prefix of `cand`.
  // The end is free on the candidate side, which is what makes this a
  // completion through an error rather than a whole-word correction.
  function alignScore(typed, cand) {
    var n = typed.length;
    var maxJ = Math.min(cand.length, n + 2);
    if (cand.length < n - 2) return null;

    // prev2 / prev / cur are rows of the DP table, kept as three arrays rather
    // than a matrix because only the last two are ever read.
    var NEG = -Infinity;
    var prev2 = null;
    var prev = new Array(maxJ + 1);
    var cur = new Array(maxJ + 1);
    var i, j, best, viaSub, viaExtra, viaOmit, viaSwap;

    for (j = 0; j <= maxJ; j++) prev[j] = j * LOG_OMIT; // i = 0: all omissions

    for (i = 1; i <= n; i++) {
      cur[0] = i * LOG_EXTRA; // j = 0: everything typed was an extra click
      for (j = 1; j <= maxJ; j++) {
        viaSub = prev[j - 1] + subCost(typed.charAt(i - 1), cand.charAt(j - 1));
        viaExtra = prev[j] + LOG_EXTRA;
        viaOmit = cur[j - 1] + LOG_OMIT;
        best = viaSub > viaExtra ? viaSub : viaExtra;
        if (viaOmit > best) best = viaOmit;
        if (
          i >= 2 && j >= 2 && prev2 &&
          typed.charAt(i - 1) === cand.charAt(j - 2) &&
          typed.charAt(i - 2) === cand.charAt(j - 1)
        ) {
          viaSwap = prev2[j - 2] + LOG_TRANSPOSE;
          if (viaSwap > best) best = viaSwap;
        }
        cur[j] = best;
      }
      prev2 = prev;
      prev = cur;
      cur = new Array(maxJ + 1);
      if (i === n) break;
    }

    // Free end: the alignment may stop anywhere sensible in the candidate.
    best = NEG;
    var from = Math.max(0, n - 2);
    for (j = from; j <= maxJ; j++) {
      if (prev[j] > best) best = prev[j];
    }
    return best === NEG ? null : best;
  }

  // BIGRAMS is a plain object, so a previous word that collides with a member
  // of Object.prototype returns an inherited function rather than a bucket or
  // undefined. space() commits whatever was typed, dictionary word or not, so
  // typing "constructor" and pressing space is enough to reach it: the lookup
  // yielded the Object constructor, which is truthy and has no indexOf, and
  // every later keystroke threw out of predict(). Own properties only.
  function bigramsFor(prevWord) {
    if (!prevWord) return null;
    if (!Object.prototype.hasOwnProperty.call(BIGRAMS, prevWord)) return null;
    var bucket = BIGRAMS[prevWord];
    return bucket && bucket.length ? bucket : null;
  }

  function bigramBonus(prevWord, word) {
    var bucket = bigramsFor(prevWord);
    if (!bucket) return 0;
    var at = bucket.indexOf(word);
    if (at < 0) return 0;
    // The curated pairs are ordered by usage, so earlier entries are worth
    // more. This is a stand-in for the real engine's context probability
    // blend, not a reproduction of it.
    return 2.2 - Math.min(at, 6) * 0.15;
  }

  function nextWordSuggestions(prevWord) {
    var out = [], seen = Object.create(null), i;
    var bucket = bigramsFor(prevWord);
    if (bucket) {
      for (i = 0; i < bucket.length && out.length < MAX_PILLS; i++) {
        if (!seen[bucket[i]]) { seen[bucket[i]] = 1; out.push(bucket[i]); }
      }
    }
    for (i = 0; i < WORDS.length && out.length < MAX_PILLS; i++) {
      if (!seen[WORDS[i]]) { seen[WORDS[i]] = 1; out.push(WORDS[i]); }
    }
    return out;
  }

  function predict(typed, prevWord) {
    if (!typed) return nextWordSuggestions(prevWord);

    var exact = [];
    var i, w, idx, score;

    // Exact prefix completions. These are what the n-gram half of the real
    // engine contributes, and they are protected from being outranked below.
    var bucket = BY_FIRST[typed.charAt(0)] || [];
    for (i = 0; i < bucket.length; i++) {
      idx = bucket[i];
      w = WORDS[idx];
      if (w.length >= typed.length && w.lastIndexOf(typed, 0) === 0) {
        exact.push({ word: w, score: freqScore(idx) + bigramBonus(prevWord, w), exact: true });
      }
    }
    exact.sort(function (a, b) { return b.score - a.score; });

    var fuzzy = [];
    if (typed.length >= MIN_FUZZY_PREFIX) {
      // Prune to words whose first letter could plausibly be what was aimed
      // at: the typed letter, one of its neighbours, or the second typed
      // letter if the first click was missed entirely.
      var firsts = {};
      (NEIGHBOURS[typed.charAt(0)] || [typed.charAt(0)]).forEach(function (c) { firsts[c] = 1; });
      firsts[typed.charAt(0)] = 1;
      if (typed.length > 1) firsts[typed.charAt(1)] = 1;

      Object.keys(firsts).forEach(function (letter) {
        var list = BY_FIRST[letter];
        if (!list) return;
        for (var k = 0; k < list.length; k++) {
          var j = list[k], cand = WORDS[j];
          if (cand.length < typed.length - MAX_EXTRA_KEYS) continue;
          if (cand.lastIndexOf(typed, 0) === 0) continue; // already an exact hit
          var path = alignScore(typed, cand);
          if (path === null) continue;
          if (cand.charAt(0) !== typed.charAt(0)) path += FIRST_KEY_ANCHOR;
          if (path < -7) continue;
          fuzzy.push({ word: cand, score: path + freqScore(j), path: path, exact: false });
        }
      });
      fuzzy.sort(function (a, b) { return b.score - a.score; });
    }

    // Merge. A fuzzy candidate reached only by paths costing more than one
    // cheap edit sits below every exact completion rather than being bought
    // past them by frequency; one that is within a cheap edit competes
    // normally, which is what lets "teh" still offer "the" first.
    var cheap = [], dear = [];
    fuzzy.forEach(function (c) {
      (c.path >= FREQUENCY_MAY_BUY ? cheap : dear).push(c);
    });

    var merged = exact.concat(cheap);
    merged.sort(function (a, b) { return b.score - a.score; });
    merged = merged.concat(dear);

    var out = [], seen = Object.create(null);
    for (i = 0; i < merged.length && out.length < MAX_PILLS; i++) {
      if (seen[merged[i].word]) continue;
      seen[merged[i].word] = 1;
      out.push(merged[i].word);
    }
    return out;
  }

  /* ---------- View ---------- */

  function init() {
    var root = document.getElementById("kbdemo");
    if (!root) return;

    var data = window.ALPHA_OSK_DEMO_DATA;
    var statusEl = root.querySelector("[data-demo-status]");
    if (!data || !data.words || !data.words.length) {
      // The dictionary is a separate file; if it did not arrive, say so rather
      // than presenting a keyboard whose pills silently never fill in.
      if (statusEl) {
        statusEl.textContent =
          "The demo dictionary could not be loaded, so suggestions are unavailable. " +
          "The keyboard itself is unaffected in the real application.";
        statusEl.hidden = false;
      }
      root.setAttribute("data-demo-broken", "true");
      return;
    }

    WORDS = data.words;
    BIGRAMS = data.bigrams || {};
    buildIndexes();

    var textEl = root.querySelector("[data-demo-text]");
    var placeholderEl = root.querySelector("[data-demo-placeholder]");
    var pillsEl = root.querySelector("[data-demo-pills]");
    var keysEl = root.querySelector("[data-demo-keys]");
    var savedEl = root.querySelector("[data-demo-saved]");
    var clearBtn = root.querySelector("[data-demo-clear]");
    var screenEl = root.querySelector("[data-demo-screen]");

    var committed = [];  // finished words
    var current = "";    // word in progress
    var saved = 0;       // clicks prediction has saved

    function prevWord() {
      return committed.length ? committed[committed.length - 1] : "";
    }

    function sentence() {
      var s = committed.join(" ");
      if (current) s = s ? s + " " + current : current;
      else if (committed.length) s += " ";
      return s;
    }

    function renderText() {
      var s = sentence();
      textEl.textContent = s;
      placeholderEl.hidden = s.length > 0;
    }

    function renderSaved() {
      savedEl.textContent = saved === 0
        ? "No clicks saved yet. Take a suggestion above."
        : saved + (saved === 1 ? " click saved" : " clicks saved") + " so far.";
    }

    function renderPills() {
      var words = predict(current, prevWord());
      var kids = pillsEl.children;

      // Update the buttons in place instead of clearing and rebuilding. Every
      // keystroke re-renders, so a rebuild destroyed the button the user was
      // standing on: taking a suggestion from the keyboard dropped focus to
      // <body> and the next Tab restarted from the top of the document.
      if (words.length && document.activeElement &&
          document.activeElement.parentNode === pillsEl) {
        var at = Array.prototype.indexOf.call(kids, document.activeElement);
        // Focus is on a pill that is about to go. Keep it in the group.
        if (at >= words.length) kids[words.length - 1].focus();
      }

      while (kids.length > words.length) pillsEl.removeChild(pillsEl.lastChild);

      for (var i = 0; i < words.length; i++) {
        var b = kids[i];
        if (!b) {
          b = document.createElement("button");
          b.type = "button";
          b.className = "kbdemo__pill";
          // The visible word is the accessible name, and the surrounding group
          // is labelled "Word suggestions", so the button does not repeat it.
          // The handler reads the label at click time rather than closing over
          // it, because the button now outlives any one suggestion.
          b.addEventListener("click", function () { takePill(this.textContent); });
          pillsEl.appendChild(b);
        }
        b.textContent = words[i];
      }
    }

    function render() {
      renderText();
      renderPills();
      renderSaved();
    }

    function takePill(word) {
      // A pill is worth the characters it did not make you click, plus the
      // space it inserts for you. This is the same accounting the application's
      // keystrokes-saved figure uses.
      var gain = word.length - current.length + 1;
      if (gain > 0) saved += gain;
      committed.push(word);
      current = "";
      render();
    }

    function typeChar(ch) {
      current += ch;
      render();
    }

    function backspace() {
      if (current) {
        current = current.slice(0, -1);
      } else if (committed.length) {
        // Step back into the previous word so backspacing behaves the way it
        // does in a real field rather than deleting a whole word at a time.
        // No slice: sentence() renders a trailing space after a committed
        // word, so that space is the one character on screen this press is
        // removing. Slicing here spent a single click on two deletions, which
        // is the exact cost this panel is arguing against.
        current = committed.pop();
      }
      render();
    }

    function space() {
      if (!current) return;
      committed.push(current);
      current = "";
      render();
    }

    function clearAll() {
      committed = [];
      current = "";
      saved = 0;
      render();
    }

    /* ---- keyboard ---- */

    function addKey(row, label, name, cls, handler) {
      var b = document.createElement("button");
      b.type = "button";
      b.className = "kbdemo__key" + (cls ? " " + cls : "");
      b.textContent = label;
      if (name) b.setAttribute("aria-label", name);
      b.addEventListener("click", handler);
      row.appendChild(b);
      return b;
    }

    var letterKeys = {};
    ROWS.forEach(function (letters, rowIndex) {
      var row = document.createElement("div");
      row.className = "kbdemo__row";
      // The stagger is the real board's, from the same table the spatial model
      // uses, so the keys line up with the positions predictions are scored in.
      if (rowIndex === 1) row.style.paddingInline = "2.5%";
      if (rowIndex === 2) row.style.paddingInline = "7.5%";
      letters.forEach(function (ch) {
        letterKeys[ch] = addKey(row, ch, null, null, function () { typeChar(ch); });
      });
      if (rowIndex === 2) {
        addKey(row, "⌫", "Backspace", "kbdemo__key--wide", backspace);
      }
      keysEl.appendChild(row);
    });

    var lastRow = document.createElement("div");
    lastRow.className = "kbdemo__row";
    addKey(lastRow, "space", "Space", "kbdemo__key--space", space);
    keysEl.appendChild(lastRow);

    /* ---- physical keyboard ---- */

    // The panel is focusable so somebody using a real keyboard can drive the
    // demo with it. Scoping the handler to the panel rather than the document
    // is deliberate: a page-wide key handler would swallow ordinary typing and
    // browser shortcuts everywhere else on the site.
    screenEl.addEventListener("keydown", function (e) {
      if (e.ctrlKey || e.metaKey || e.altKey) return;
      var k = e.key;
      if (k.length === 1 && k >= "a" && k <= "z") {
        typeChar(k);
      } else if (k.length === 1 && k >= "A" && k <= "Z") {
        typeChar(k.toLowerCase());
      } else if (k === "Backspace") {
        backspace();
      } else if (k === " ") {
        space();
      } else {
        return;
      }
      e.preventDefault();
      // Flash the on-screen key so the two inputs read as the same keyboard.
      var key = letterKeys[k.toLowerCase()];
      if (key) {
        key.setAttribute("data-pressed", "true");
        window.setTimeout(function () { key.removeAttribute("data-pressed"); }, 120);
      }
    });

    clearBtn.addEventListener("click", function () {
      clearAll();
      screenEl.focus();
    });

    root.setAttribute("data-demo-ready", "true");
    render();
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
})();
